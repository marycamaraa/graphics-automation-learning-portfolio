//--------------------------------------------------------------------------------------
// ==============================
//*      DOCKER
// ==============================

/*
- Docker is a platform that allows developers to create, deploy, and run applications in containers. 
- Containers are lightweight, portable, and self-sufficient environments that can run consistently across different computing environments.
- Docker provides a way to package an application and its dependencies into a single unit called a Docker image.
- Docker images can be easily shared and deployed on any system that has Docker installed, making it easier to manage and scale applications.
*/

//--------------------------------------------------------------------------------------
// ==============================
//*      DOCKER PLATFORM
// ==============================

/*
- Docker can be used on various platforms, including Windows, macOS, and Linux.
- Docker Desktop is available for Windows and macOS, providing a user-friendly interface for managing Docker containers and images.
- On Linux, Docker can be installed directly using package managers like apt or yum.
- Docker can also be used in cloud environments, such as AWS, Azure, and Google Cloud,
 allowing developers to deploy and manage applications in the cloud.

*/

//--------------------------------------------------------------------------------------
// ==============================
//*      DOCKER CONTAINERS
// ==============================

/*
- Docker containers are isolated environments that run applications and their dependencies.
- Containers share the host operating system's kernel but have their own filesystem, network, and process space.
- This isolation allows multiple containers to run on the same host without interfering with each other.
- Containers can be started, stopped, and managed using Docker commands, making it easy to deploy and scale applications.

*/

//--------------------------------------------------------------------------------------
// ==============================
//*      DOCKER IMAGES
// ==============================

/*
- Docker images are read-only templates that contain the application code, libraries, and dependencies needed to run an application.
- Images are built using a Dockerfile, which is a text file that contains instructions for building the image.
- Once an image is built, it can be run as a container on any system with Docker installed.
- Images can be shared and distributed through Docker Hub or other container registries, making it easy to collaborate and deploy applications.

*/

//--------------------------------------------------------------------------------------
// ==============================
//*     LIFECYCLE MANAGEMENT WITH DOCKER
// ==============================

/*
- Docker you development your application using containers, you can easily manage the lifecycle of your application.
- You can start, stop, and restart containers as needed, allowing you to quickly iterate on your application during development.
- Docker also provides features like volume management and networking, making it easier to manage data and communication between containers.
- For production deployments, Docker can be used in conjunction with orchestration tools like Kubernetes to manage the lifecycle of applications at scale.

*/

